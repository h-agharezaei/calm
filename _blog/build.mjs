    const L = LANGS[lang];
    const cat = L.categories[post.category];
    const image = SITE + (post.cover || '/assets/images/og.jpg');
    const box = sessionBoxHtml(post, L);
    const { html, faq } = renderMarkdown(post.body, box, L.faqHeading);
    const blogUrl = SITE + L.base;

    const ld = [
        {
            '@context': 'https://schema.org',
            '@type': 'BlogPosting',
            headline: post.title,
            description: post.description,
            image: [image],
            datePublished: post.date,
            dateModified: post.updated || post.date,
            inLanguage: L.inLanguage,
            mainEntityOfPage: post.url,
            author: { '@type': 'Organization', name: 'Calm', url: SITE + '/' },
            publisher: {
                '@type': 'Organization', name: 'Calm', url: SITE + '/',
                logo: { '@type': 'ImageObject', url: SITE + '/assets/icons/icon-512.png' }
            },
            ...(cat ? { articleSection: cat.single } : {}),
            ...(translation ? {
                [lang === DEFAULT_LANG ? 'workTranslation' : 'translationOfWork']:
                    { '@type': 'BlogPosting', url: translation.url, inLanguage: LANGS[translation.lang].inLanguage }
            } : {}),
            wordCount: post.words
        },
        {
            '@context': 'https://schema.org',
            '@type': 'BreadcrumbList',
            itemListElement: [
                { '@type': 'ListItem', position: 1, name: 'Calm', item: SITE + homeUrl(lang) },
                { '@type': 'ListItem', position: 2, name: L.t.blog, item: blogUrl },
                { '@type': 'ListItem', position: 3, name: post.title, item: post.url }
            ]
        }
    ];
